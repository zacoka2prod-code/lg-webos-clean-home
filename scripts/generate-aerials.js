#!/usr/bin/env node

// Regenerate src/js/aerials.js: the vendored catalog of Apple's aerial clips.
//
//   node scripts/generate-aerials.js
//
// Fetches conreo/couchy-launcher's aerials.json, keeps the Apple entries
// (s === "A"), slugs each title into a stable id and writes the catalog as a
// committed ES module. Run by hand; the output is committed, so the app never
// touches the network for the catalog.

const fs = require('fs');
const https = require('https');
const path = require('path');

const SOURCE_URL =
  'https://raw.githubusercontent.com/conreo/couchy-launcher/main/app/src/main/assets/aerials.json';
const OUT_FILE = path.resolve(__dirname, '..', 'src', 'js', 'aerials.js');
const ID_PREFIX = 'aerial-apple-';

function fetchJson(url) {
  return new Promise(function (resolve, reject) {
    https.get(url, function (res) {
      if (res.statusCode !== 200) {
        res.resume();
        reject(new Error('HTTP ' + res.statusCode + ' for ' + url));
        return;
      }
      let body = '';
      res.setEncoding('utf8');
      res.on('data', function (chunk) { body += chunk; });
      res.on('end', function () {
        try {
          resolve(JSON.parse(body));
        } catch (err) {
          reject(err);
        }
      });
    }).on('error', reject);
  });
}

function slugify(title) {
  return String(title)
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function buildCatalog(raw) {
  const list = Array.isArray(raw) ? raw : [];
  const seen = {};
  const catalog = [];

  list.forEach(function (entry) {
    if (!entry || entry.s !== 'A') return;
    const title = String(entry.t || '').trim();
    const url = String(entry.u || '').trim();
    if (!title || !url) return;

    let id = ID_PREFIX + slugify(title);
    if (seen[id]) {
      let n = 2;
      while (seen[id + '-' + n]) n += 1;
      id = id + '-' + n;
    }
    seen[id] = true;
    catalog.push({id: id, title: title, url: url});
  });

  return catalog;
}

function quote(value) {
  return "'" + String(value)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n') + "'";
}

function renderModule(catalog) {
  const lines = catalog.map(function (entry) {
    return '  {id: ' + quote(entry.id) +
      ', title: ' + quote(entry.title) +
      ', url: ' + quote(entry.url) + '}';
  });

  return [
    '// GENERATED by scripts/generate-aerials.js — do not edit by hand.',
    '//',
    '// Apple\'s aerial clips (139), vendored from conreo/couchy-launcher\'s',
    '// aerials.json (entries where s === "A"). Ids are stable slugs of the',
    '// titles. The clips stream from Apple\'s CDN and are never packaged.',
    '// Regenerate with: node scripts/generate-aerials.js',
    '',
    'export const AERIAL_BACKGROUNDS = [',
    lines.join(',\n'),
    '];',
    ''
  ].join('\n');
}

async function main() {
  const raw = await fetchJson(SOURCE_URL);
  const catalog = buildCatalog(raw);
  if (!catalog.length) {
    throw new Error('No Apple aerial entries found in ' + SOURCE_URL);
  }
  fs.writeFileSync(OUT_FILE, renderModule(catalog));
  console.log('Wrote ' + catalog.length + ' aerial clips to ' + path.relative(process.cwd(), OUT_FILE));
}

main().catch(function (err) {
  console.error(err);
  process.exit(1);
});
